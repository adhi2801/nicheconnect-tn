// Reads tokens/tokens.json (W3C Design Tokens, colours in OKLCH) and writes what consumes it:
//   packages/tokens/tokens.css          the website: CSS variables per theme and brand
//   packages/tokens/tokens.resolved.json  every colour as hex with its contrast checks, for the catalogue page
//   packages/tokens/colyv_tokens.dart   the app
// Then checks every text and background pair the source lists, in every theme and brand,
// and exits 1 if one misses its bar (docs/standards/frontend.md section 6).
//
// No dependency: OKLCH to sRGB is Björn Ottosson's published matrices (https://bottosson.github.io/posts/oklab/),
// out-of-gamut colours are brought in by lowering chroma (as CSS Color 4 gamut mapping does, simplified),
// and contrast is WCAG 2.2's relative-luminance ratio.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("../tokens/tokens.json", import.meta.url), "utf8"));
const out = new URL("../packages/tokens/", import.meta.url);
mkdirSync(out, { recursive: true });

// ---------- colour ----------

function oklchToLinear([L, C, h]) {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}
const inGamut = (rgb) => rgb.every((v) => v >= -1e-4 && v <= 1 + 1e-4);
function toLinearInGamut([L, C, h]) {
  let rgb = oklchToLinear([L, C, h]);
  if (inGamut(rgb)) return { rgb, clipped: false };
  let lo = 0, hi = C;
  for (let i = 0; i < 30; i++) {
    const mid = (lo + hi) / 2;
    if (inGamut(oklchToLinear([L, mid, h]))) lo = mid; else hi = mid;
  }
  return { rgb: oklchToLinear([L, lo, h]), clipped: true };
}
const encode = (v) => {
  v = Math.min(1, Math.max(0, v));
  return v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
};
const decode = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
function hexOf(components) {
  const { rgb, clipped } = toLinearInGamut(components);
  const hex = "#" + rgb.map((v) => Math.round(encode(v) * 255).toString(16).padStart(2, "0")).join("").toUpperCase();
  return { hex, clipped };
}
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => decode(parseInt(hex.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

// ---------- resolve the palettes ----------

const tokens = (group) => Object.fromEntries(Object.entries(group).filter(([k]) => !k.startsWith("$")));
const colours = (group) => {
  const res = {};
  for (const [name, tok] of Object.entries(tokens(group))) {
    const { hex, clipped } = hexOf(tok.$value.components);
    if (clipped) console.warn(`note: ${name} is outside sRGB; chroma lowered to fit`);
    res[name] = hex;
  }
  return res;
};

const THEMES = ["light", "dark"];
const BRANDS = Object.keys(tokens(t.brand));
const DEFAULT_BRAND = "burgundy";
const resolved = {};
for (const theme of THEMES) {
  const base = colours(t.theme[theme]);
  for (const brand of BRANDS) resolved[`${theme}/${brand}`] = { ...base, ...colours(t.brand[brand][theme]) };
}

// ---------- contrast ----------

const failures = [];
const checks = {};
for (const [key, palette] of Object.entries(resolved)) {
  checks[key] = t.contrast.pairs.map(([fg, bg, min]) => {
    if (!palette[fg] || !palette[bg]) throw new Error(`contrast pair ${fg}/${bg}: no such colour`);
    const ratio = contrast(palette[fg], palette[bg]);
    if (ratio < min) failures.push(`${key}: ${fg} on ${bg} is ${ratio.toFixed(2)}:1, needs ${min}:1`);
    return { fg, bg, min, ratio: Math.round(ratio * 100) / 100 };
  });
}

// ---------- CSS ----------

const px = (d) => `${d.value}${d.unit}`;
const ms = (d) => `${d.value}${d.unit}`;
const bezier = (v) => `cubic-bezier(${v.join(", ")})`;
const aliases = t.legacy.aliases;
const block = (palette) => {
  let s = "";
  for (const [k, v] of Object.entries(palette)) s += `  --c-${k}: ${v};\n`;
  for (const [old, now] of Object.entries(aliases)) s += `  --c-${old}: var(--c-${now});\n`;
  return s;
};
const elevation = (theme) => Object.entries(t.elevation[theme]).map(([k, v]) => `  --e-${k}: ${v};\n`).join("");

let css = "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */\n\n";
css += ":root {\n  color-scheme: light;\n";
for (const [k, v] of Object.entries(tokens(t.space))) css += `  --s-${k}: ${px(v.$value)};\n`;
for (const [k, v] of Object.entries(tokens(t.radius))) css += `  --r-${k}: ${px(v.$value)};\n`;
for (const [k, v] of Object.entries(tokens(t.font))) css += `  --f-${k}: ${v.$value.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ")};\n`;
for (const [k, v] of Object.entries(tokens(t.type))) {
  const x = v.$value;
  css += `  --t-${k}-size: ${px(x.fontSize)};\n  --t-${k}-leading: ${x.lineHeight};\n  --t-${k}-weight: ${x.fontWeight};\n  --t-${k}-tracking: ${x.letterSpacing.value}${x.letterSpacing.unit};\n`;
}
for (const [k, v] of Object.entries(tokens(t.duration))) css += `  --m-${k}: ${ms(v.$value)};\n`;
for (const [k, v] of Object.entries(tokens(t.easing))) css += `  --ease-${k}: ${bezier(v.$value)};\n`;
// the first design system's motion names
css += "  --m-fast: var(--m-press);\n  --m-base: var(--m-state);\n  --m-slow: var(--m-section);\n  --m-ease: var(--ease-standard);\n";
css += elevation("light");
css += block(resolved[`light/${DEFAULT_BRAND}`]);
css += "}\n\n";
for (const brand of BRANDS.filter((b) => b !== DEFAULT_BRAND)) {
  css += `[data-brand="${brand}"] {\n`;
  for (const [k, v] of Object.entries(colours(t.brand[brand].light))) css += `  --c-${k}: ${v};\n`;
  css += "}\n\n";
}
// Dark is opt-in (data-theme="dark") until every component passes its dark screenshots;
// then this becomes a prefers-color-scheme rule too.
css += `[data-theme="dark"] {\n  color-scheme: dark;\n${elevation("dark")}${block(resolved[`dark/${DEFAULT_BRAND}`])}}\n\n`;
for (const brand of BRANDS.filter((b) => b !== DEFAULT_BRAND)) {
  css += `[data-theme="dark"][data-brand="${brand}"], [data-theme="dark"] [data-brand="${brand}"] {\n`;
  for (const [k, v] of Object.entries(colours(t.brand[brand].dark))) css += `  --c-${k}: ${v};\n`;
  css += "}\n\n";
}
writeFileSync(new URL("tokens.css", out), css);

writeFileSync(
  new URL("tokens.resolved.json", out),
  JSON.stringify({ defaultBrand: DEFAULT_BRAND, themes: THEMES, brands: BRANDS, colours: resolved, contrast: checks }, null, 2) + "\n",
);

// ---------- Dart ----------

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const argb = (hex) => `Color(0xFF${hex.slice(1)})`;
let dart = "// Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit.\nimport 'dart:ui';\n\n";
dart += "/// One theme and brand's colours.\nclass ColyvPalette {\n";
const names = Object.keys(resolved[`light/${DEFAULT_BRAND}`]);
dart += "  const ColyvPalette({\n" + names.map((n) => `    required this.${camel(n)},\n`).join("") + "  });\n";
dart += names.map((n) => `  final Color ${camel(n)};\n`).join("");
dart += "}\n\nclass ColyvTokens {\n";
for (const [key, palette] of Object.entries(resolved)) {
  const [theme, brand] = key.split("/");
  dart += `  static const ${camel(`${theme}-${brand}`)} = ColyvPalette(\n` + names.map((n) => `    ${camel(n)}: ${argb(palette[n])},\n`).join("") + "  );\n";
}
const light = resolved[`light/${DEFAULT_BRAND}`];
dart += "\n  // The first design system's names, kept so existing screens build.\n";
for (const n of names) dart += `  static const ${camel("c-" + n)} = ${argb(light[n])};\n`;
for (const [old, now] of Object.entries(aliases)) dart += `  static const ${camel("c-" + old)} = ${argb(light[now])};\n`;
for (const [k, v] of Object.entries(tokens(t.space))) dart += `  static const double s${k.replace("-", "_")} = ${v.$value.value};\n`;
for (const [k, v] of Object.entries(tokens(t.radius))) dart += `  static const double r${k[0].toUpperCase()}${k.slice(1)} = ${v.$value.value};\n`;
for (const [k, v] of Object.entries(tokens(t.duration))) dart += `  static const motion${k[0].toUpperCase()}${k.slice(1)} = Duration(milliseconds: ${v.$value.value});\n`;
dart += `  static const motionFast = motionPress;\n  static const motionBase = motionState;\n  static const motionSlow = motionSection;\n}\n`;
writeFileSync(new URL("colyv_tokens.dart", out), dart);
try { writeFileSync(new URL("../apps/mobile/lib/colyv_tokens.dart", import.meta.url), dart); } catch {}

// ---------- report ----------

const total = Object.values(checks).reduce((n, c) => n + c.length, 0);
if (failures.length) {
  console.error(`contrast: ${failures.length} of ${total} pairs fail\n  ` + failures.join("\n  "));
  process.exit(1);
}
const weakest = Object.entries(checks)
  .flatMap(([k, c]) => c.map((x) => ({ k, ...x, margin: x.ratio / x.min })))
  .sort((a, b) => a.margin - b.margin)[0];
console.log(`tokens written; contrast: all ${total} pairs pass (closest: ${weakest.k} ${weakest.fg} on ${weakest.bg}, ${weakest.ratio}:1 for ${weakest.min}:1)`);

// Reads tokens/tokens.json and writes the two things that consume it:
// packages/tokens/tokens.css (website) and packages/tokens/colyv_tokens.dart (app, later).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("../tokens/tokens.json", import.meta.url), "utf8"));
const out = new URL("../packages/tokens/", import.meta.url);
mkdirSync(out, { recursive: true });

const px = (n) => `${n}px`;
let css = "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */\n:root {\n";
for (const [k, v] of Object.entries(t.color)) css += `  --c-${k}: ${v};\n`;
for (const [k, v] of Object.entries(t.space)) css += `  --s-${k}: ${px(v)};\n`;
for (const [k, v] of Object.entries(t.radius)) css += `  --r-${k}: ${px(v)};\n`;
for (const [k, v] of Object.entries(t.motion)) css += `  --m-${k}: ${typeof v === "number" ? v + "ms" : v};\n`;
for (const [k, v] of Object.entries(t.type)) css += `  --f-${k}: ${v};\n`;
css += "}\n";
writeFileSync(new URL("tokens.css", out), css);

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const argb = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
let dart = "// Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit.\nimport 'dart:ui';\n\nclass ColyvTokens {\n";
for (const [k, v] of Object.entries(t.color)) dart += `  static const ${camel("c-" + k)} = ${argb(v)};\n`;
for (const [k, v] of Object.entries(t.space)) dart += `  static const double s${k} = ${v};\n`;
for (const [k, v] of Object.entries(t.radius)) dart += `  static const double r${k[0].toUpperCase()}${k.slice(1)} = ${v};\n`;
dart += `  static const motionFast = Duration(milliseconds: ${t.motion.fast});\n  static const motionBase = Duration(milliseconds: ${t.motion.base});\n  static const motionSlow = Duration(milliseconds: ${t.motion.slow});\n}\n`;
writeFileSync(new URL("colyv_tokens.dart", out), dart);
try { writeFileSync(new URL("../apps/mobile/lib/colyv_tokens.dart", import.meta.url), dart); } catch {}
console.log("tokens written");
